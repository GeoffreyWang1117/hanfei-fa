"""Golden vectors for the v1 hashing convention.

``tests/vectors/format_v1.json`` was generated by the merkle-weight-verify 0.2.0
release as published on PyPI. Every later version must reproduce these roots
exactly when building v1 trees; otherwise existing ``.merkle.json`` manifests
would stop verifying.
"""

import io
import json
from pathlib import Path

import pytest

from merkle_verify import MerkleTree, build_model_merkle_tree

VECTORS = json.loads((Path(__file__).parent / "vectors" / "format_v1.json").read_text())


def blob(seed, n):
    return bytes((seed * 131 + i * 7) % 256 for i in range(n))


def test_generated_by_020():
    assert VECTORS["generated_by"] == "merkle-weight-verify 0.2.0"


@pytest.mark.parametrize("case", VECTORS["chunk_trees"], ids=lambda c: f"n={len(c['leaves'])}")
def test_chunk_tree_roots(case):
    assert MerkleTree(case["leaves"], chunk_size=16).root_hash == case["root"]


@pytest.mark.parametrize("chunk_size", sorted(VECTORS["model"]["by_chunk_size"], key=int))
@pytest.mark.parametrize("parallel", [False, True])
def test_model_roots(chunk_size, parallel):
    spec = VECTORS["model"]
    blobs = {name: blob(*v["seed_len"]) for name, v in spec["blobs"].items()}
    expected = spec["by_chunk_size"][chunk_size]
    tree = build_model_merkle_tree(
        blobs, chunk_size=int(chunk_size), model_name="golden", parallel=parallel, num_workers=4
    )
    assert tree.model_root == expected["model_root"]
    assert {k: v.layer_root for k, v in tree.layer_trees.items()} == expected["layer_roots"]
    params = {p: pt.root_hash for lt in tree.layer_trees.values() for p, pt in lt.param_trees.items()}
    assert params == expected["param_roots"]


def test_file_root():
    spec = VECTORS["file"]
    data = blob(*spec["seed_len"])
    assert MerkleTree.from_file(io.BytesIO(data), spec["chunk_size"]).root_hash == spec["root"]
